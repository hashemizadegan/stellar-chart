    # عشق و روابط
    v = _sign(chart, "Venus")
    love = f"با زهره در {N[v]}، شما {SIGNS[v]['style']} عشق می‌ورزید."
    love += _house_sentence(chart, "Venus", "زندگی عاطفی شما بیشتر با حوزهٔ {h} گره خورده است.")
    love += f" به آدم‌هایی جذب می‌شوید که {SIGNS[v]['traits'][0]} و {SIGNS[v]['traits'][1]} هستند."
    if known and chart.get("houses"):
        seventh = chart["houses"][6]["sign"]
        love += (f" خانهٔ هفتم شما (خانهٔ شراکت) در {N[seventh]} آغاز می‌شود، پس همراهی "
                 f"{SIGNS[seventh]['traits'][0]} و {SIGNS[seventh]['traits'][1]} معمولاً تعادل خوبی به زندگی‌تان می‌آورد.")
    love += (f" با ماه در {N[moon]}، کنار کسی احساس امنیت عاطفی می‌کنید که به شما اجازه دهد "
             f"{SIGNS[moon]['style']} با او ارتباط بگیرید.")
    s.append(("عشق و روابط", [love]))

    # کار و هدف زندگی
    m = _sign(chart, "Mars")
    work = f"مریخ در {N[m]} نشان می‌دهد چگونه به‌سوی اهدافتان می‌روید: {SIGNS[m]['style']}."
    work += _house_sentence(chart, "Mars", "انرژی کاری شما بیشتر در حوزهٔ {h} صرف می‌شود.")
    if known and chart.get("angles"):
        mc = chart["angles"]["Midheaven"]["sign"]
        tenth = [PLANET_NAMES[b] for b, d in p.items() if d.get("house") == 10 and b != "North Node"]
        work += (f" میانه‌آسمان شما در {N[mc]} از مسیری اجتماعی خبر می‌دهد که در آن بتوانید "
                 f"{SIGNS[mc]['style']} کار کنید، و نقش‌هایی که {SIGNS[mc]['traits'][1]} بودن را ارج می‌نهند "
                 "برایتان مناسب‌اند.")
        if tenth:
            work += (f" با قرار گرفتن {_join(tenth)} در خانهٔ دهم، شغل و اعتبار اجتماعی موضوعی مهم در زندگی "
                     "شماست و دیگران دستاوردهایتان را می‌بینند.")
    node = _sign(chart, "North Node")
    work += (f" گره شمالی در {N[node]} به هدف بلندمدت زندگی شما اشاره دارد: بیشترین رشد را زمانی تجربه "
             f"می‌کنید که یاد بگیرید {SIGNS[node]['style']} زندگی کنید.")
    s.append(("کار و هدف زندگی", [work]))

    return "\n\n".join(f"## {title}\n" + "\n\n".join(paras) for title, paras in s)
