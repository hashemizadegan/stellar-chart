def _join(items):
    return items[0] if len(items) == 1 else "، ".join(items[:-1]) + " و " + items[-1]


def _sign(chart, body):
    return chart["planets"][body]["sign"]


def _house_sentence(chart, body, template):
    h = chart["planets"][body].get("house")
    return " " + template.format(h=HOUSES[h]) if h else ""


def _aspect_name(a):
    return f"{ASPECT_NAMES[a['aspect']]} {PLANET_NAMES[a['a']]} و {PLANET_NAMES[a['b']]}"


def _aspect_body(a):
    return ASPECT_TEXT[a["aspect"]].format(a=PLANET_KEYS[a["a"]], b=PLANET_KEYS[a["b"]])


def natal_report_fa(name: str, chart: dict) -> str:
    p = chart["planets"]
    sun, moon = _sign(chart, "Sun"), _sign(chart, "Moon")
    rising = chart["summary"].get("rising")
    known = chart.get("time_known", False)
    first = name.split()[0] if name else ""
    elements = chart["elements"]
    strong = max(elements, key=elements.get)
    weak = min(elements, key=elements.get)
    aspects = [a for a in chart["aspects"] if "North Node" not in (a["a"], a["b"])]
    easy = [a for a in aspects if a["aspect"] in ("trine", "sextile")]
    hard = [a for a in aspects if a["aspect"] in ("square", "opposition")]
    N = SIGN_NAMES
    s = []

    # نگاه کلی
    greet = f"{first} عزیز، " if first else ""
    ov = (f"{greet}چارت شما ترکیبی از خورشید در {N[sun]}، ماه در {N[moon]} و طالع {N[rising]} است." if rising
          else f"{greet}چارت شما ترکیبی از خورشید در {N[sun]} و ماه در {N[moon]} است.")
    ov += (f" قوی‌ترین عنصر چارت شما {ELEMENT_NAMES[strong]} است که به شما استعدادی طبیعی برای "
           f"{ELEMENT_STRONG[strong]} می‌دهد.")
    if elements[weak] <= 1:
        ov += f" {ELEMENT_NAMES[weak]} کم‌رنگ‌ترین عنصر چارت شماست، بنابراین {ELEMENT_WEAK[weak]}."
    retro = [PLANET_NAMES[b] for b in ("Mercury", "Venus", "Mars") if p[b]["retrograde"]]
    if retro:
        verb = "بود" if len(retro) == 1 else "بودند"
        ov += (f" {_join(retro)} در زمان تولد شما بازگشتی {verb}؛ این حالت انرژی را به درون می‌برد: "
               "پیش از عمل تأمل می‌کنید و شیوهٔ شما در این زمینه‌ها شخصی‌تر از معمول است.")
    if not known:
        ov += (" چون ساعت تولد شما مشخص نیست، این گزارش از طالع و خانه‌ها استفاده نمی‌کند، "
               "زیرا آن‌ها به دقیقهٔ دقیق تولد بستگی دارند.")
    s.append(("نگاه کلی", [ov]))

    # خورشید، ماه و طالع
    big = SUN[sun] + _house_sentence(chart, "Sun", "این ویژگی بیشتر در حوزهٔ {h} نمود پیدا می‌کند.")
    big += " " + MOON[moon]
    if rising:
        big += " " + RISING[rising]
    s.append(("خورشید، ماه و طالع", [big]))

    # جنبه‌های کلیدی
    key = aspects[:5]
    if key:
        s.append(("جنبه‌های کلیدی", [f"{_aspect_name(a)}. {_aspect_body(a)}" for a in key]))

    # نقاط قوت
    t = SIGNS[sun]["traits"]
    jup = _sign(chart, "Jupiter")
    st = (f"خورشید در {N[sun]} شما را {t[0]} و {t[1]} می‌کند و ماه در {N[moon]} به محبت شما رنگی از "
          f"{SIGNS[moon]['traits'][0]} بودن می‌دهد. مشتری در {N[jup]} نشان می‌دهد رشد و شانس کجا آسان‌تر "
          f"به سراغتان می‌آید: شما {SIGNS[jup]['style']} رشد می‌کنید.")
    st += _house_sentence(chart, "Jupiter", "این رشد بیشتر در حوزهٔ {h} رخ می‌دهد.")
    paras = [st]
    if easy:
        a = easy[0]
        paras.append(f"مفیدترین جنبهٔ چارت شما {_aspect_name(a)} است: {PLANET_KEYS[a['a']]} و "
                     f"{PLANET_KEYS[a['b']]} شما به‌نرمی با هم کار می‌کنند و این استعدادی است که ارزش پرورش دارد.")
    s.append(("نقاط قوت", paras))

    # چالش‌ها و رشد
    sat = _sign(chart, "Saturn")
    ch = (f"هر برجی روی دیگری هم دارد و برای خورشید در {N[sun]} این روی دیگر، {t[2]} بودن است. "
          "آگاهی از آن نخستین قدم برای مدیریتش است. "
          f"زحل در {N[sat]} به درس‌های زندگی شما اشاره دارد: پختگی زمانی می‌آید که یاد بگیرید "
          f"{SIGNS[sat]['style']} عمل کنید، حتی وقتی کند یا دشوار به نظر می‌رسد.")
    ch += _house_sentence(chart, "Saturn", "این درس بیشتر در حوزهٔ {h} خود را نشان می‌دهد.")
    paras = [ch]
    if hard:
        a = hard[0]
        paras.append(f"مهم‌ترین جنبهٔ رشد در چارت شما {_aspect_name(a)} است. {_aspect_body(a)}")
